export function getHurdlesForGame(game: GameMode): HurdleDefinition[] {
  return HURDLE_CATALOG.filter(h => h.game === game || h.game === 'both');
}

export function calculateDifficultyRating(hurdles: { cost: number; difficultyWeight: number }[]): number {
  if (hurdles.length === 0) return 25;
  const totalWeight = hurdles.reduce((sum, h) => sum + h.difficultyWeight, 0);
  if (totalWeight < 40) return 25;
  if (totalWeight < 75) return 50;
  if (totalWeight < 110) return 75;
  return 100;
}
